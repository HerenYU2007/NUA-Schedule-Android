const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const read = relative => fs.readFileSync(path.join(root, relative), 'utf8');
const javaRoot = 'app/src/main/java/cn/nua/wenguan/schedule/';
const main = read(javaRoot + 'MainActivity.java');
const cleanup = read(javaRoot + 'LegacySyncCleanup.java');
const settings = read('app/src/main/res/layout/activity_settings.xml');
const manifest = read('app/src/main/AndroidManifest.xml');
const sync = read('app/src/main/java/cn/nua/wenguan/schedule/ScheduleSyncActivity.java');
const screen = read('app/src/main/java/cn/nua/wenguan/schedule/SettingsActivity.java');
assert(!settings.includes('account_settings') && !settings.includes('保存登录与后台自动更新'));
assert(!manifest.includes('BackgroundSyncJobService'));
assert(!fs.existsSync(path.join(root, javaRoot + 'BackgroundSyncJobService.java')));
assert(!fs.existsSync(path.join(root, javaRoot + 'SyncSettings.java')));
assert(main.includes('LegacySyncCleanup.cancel(this)'));
assert(cleanup.includes('jobs.cancel(8417)') && !cleanup.includes('startActivity('));
for (const key of ['keep_login', 'background', 'cookie_saved', 'cookie_checked_at']) assert(cleanup.includes('.remove("' + key + '")'));
assert(!cleanup.includes('CookieManager') && !cleanup.includes('ScheduleRuleStore'));
assert(!sync.includes('background_sync') && !sync.includes('loginOnly'));
assert(sync.includes('manager.removeAllCookies'));
assert(!main.slice(main.indexOf('protected void onResume()'), main.indexOf('protected void onPause()')).includes('startActivity'));
console.log('Removed-login/background guards passed: no service/job registration/login prompt at startup, legacy cancellation, manual-only authentication and preserved schedule.');
